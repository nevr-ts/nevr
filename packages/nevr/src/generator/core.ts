/**
 * Generate Prisma schema header (generator + datasource)
 * Used for both single-file and multi-file schema generation
 */
export function generatePrismaHeader(
  options: { provider?: string; splitSchema?: boolean } = {}
): string {
  const { provider = "sqlite", splitSchema = false } = options

  // When using split schema, enable prismaSchemaFolder preview feature
  const previewFeatures = splitSchema ? `\n  previewFeatures = ["prismaSchemaFolder"]` : ""

  return `// =============================================================================
// GENERATED BY NEVR - DO NOT EDIT MANUALLY
// Regenerate with: npx nevr generate
// =============================================================================

generator client {
  provider = "prisma-client-js"${previewFeatures}
}

datasource db {
  provider = "${provider}"
  url      = env("DATABASE_URL")
}
`
}

/**
 * Inverse relation info for back-references
 */
interface InverseRelationInfo {
  fromEntity: string
  fieldName: string
  type: string
}

/**
 * Result of building relation maps for schema generation
 */
interface RelationMaps {
  /** Map of entity name to inverse relations pointing at it */
  inverseRelations: Record<string, InverseRelationInfo[]>
  /** Map of entity -> field -> relation name (for disambiguation) */
  relationNames: Record<string, Record<string, string>>
}

/**
 * Build relation maps for inverse relations and relation naming
 * This is used by both single-file and multi-file schema generators
 */
function buildRelationMaps(entities: Entity[]): RelationMaps {
  const inverseRelations: Record<string, InverseRelationInfo[]> = {}
  const relationNames: Record<string, Record<string, string>> = {}

  // First pass: collect all belongsTo relations and create inverse map
  for (const entityDef of entities) {
    const entity = resolveEntity(entityDef)
    const targetCounts: Record<string, string[]> = {}

    for (const [fieldName, field] of Object.entries(entity.config.fields)) {
      if (field.relation?.type === "belongsTo") {
        const relatedEntityOrBuilder = field.relation.entity()
        if (!relatedEntityOrBuilder) continue

        const relatedEntity = resolveEntity(relatedEntityOrBuilder)

        // Track for inverse relation
        if (!inverseRelations[relatedEntity.name]) {
          inverseRelations[relatedEntity.name] = []
        }
        inverseRelations[relatedEntity.name].push({
          fromEntity: entity.name,
          fieldName,
          type: "hasMany"
        })

        // Track for relation naming (disambiguation)
        if (!targetCounts[relatedEntity.name]) {
          targetCounts[relatedEntity.name] = []
        }
        targetCounts[relatedEntity.name].push(fieldName)
      }
    }

    // If multiple relations to same entity, we need relation names
    for (const [target, fields] of Object.entries(targetCounts)) {
      if (fields.length > 1) {
        if (!relationNames[entity.name]) relationNames[entity.name] = {}
        for (const fieldName of fields) {
          relationNames[entity.name][fieldName] = fieldName
        }
      }
    }
  }

  return { inverseRelations, relationNames }
}

/**
 * Generate Prisma models for a set of entities (without header)
 * Used for namespace-specific schema files
 */
export function generatePrismaModels(
  entities: Entity[],
  allEntities: Entity[] // All entities for relation resolution
): string {
  let schema = ""

  // Build relation maps using the shared helper
  const { inverseRelations, relationNames } = buildRelationMaps(allEntities)

  // Generate models only for the specified entities
  for (const entityDef of entities) {
    const entity = resolveEntity(entityDef)
    const modelName = pascalCase(entity.name)

    schema += `\nmodel ${modelName} {\n`
    schema += `  id            String   @id @default(uuid())\n`

    // Regular fields
    for (const [fieldName, field] of Object.entries(entity.config.fields)) {
      if (field.relation?.type === "hasMany") continue
      if (field.relation?.type === "belongsTo") continue

      const prismaType = PRISMA_TYPES[field.type] || "String"
      let line = `  ${fieldName.padEnd(12)} ${prismaType}`

      if (field.optional) line += "?"

      const attrs: string[] = []
      if (field.unique) attrs.push("@unique")
      if (field.default !== undefined) {
        if (typeof field.default === "boolean") {
          attrs.push(`@default(${field.default})`)
        } else if (typeof field.default === "number") {
          attrs.push(`@default(${field.default})`)
        } else if (typeof field.default === "string") {
          attrs.push(`@default("${field.default}")`)
        }
      }

      if (attrs.length > 0) line += " " + attrs.join(" ")
      schema += line + "\n"
    }

    // Timestamps
    if (entity.config.timestamps) {
      schema += `  createdAt     DateTime @default(now())\n`
      schema += `  updatedAt     DateTime @updatedAt\n`
    }

    // Foreign keys and relations
    const foreignKeys: string[] = []

    for (const [fieldName, field] of Object.entries(entity.config.fields)) {
      if (!field.relation) continue

      const relatedEntityOrBuilder = field.relation.entity()
      if (!relatedEntityOrBuilder) continue
      const relatedEntity = resolveEntity(relatedEntityOrBuilder)
      const relatedModel = pascalCase(relatedEntity.name)

      if (field.relation.type === "belongsTo") {
        const fk = field.relation.foreignKey
        foreignKeys.push(fk)

        schema += `  ${fk.padEnd(12)} String${field.optional ? "?" : ""}\n`

        const relName = relationNames[entity.name]?.[fieldName]
        const nameAttr = relName ? `"${relName}", ` : ""
        const onDelete = field.relation.onDelete
          ? `, onDelete: ${pascalCase(field.relation.onDelete)}`
          : ""
        schema += `  ${fieldName.padEnd(12)} ${relatedModel}? @relation(${nameAttr}fields: [${fk}], references: [id]${onDelete})\n`
      } else if (field.relation.type === "hasMany") {
        schema += `  ${fieldName.padEnd(12)} ${relatedModel}[]\n`
      } else if (field.relation.type === "hasOne") {
        schema += `  ${fieldName.padEnd(12)} ${relatedModel}?\n`
      }
    }

    // Inverse relations
    const inverses = inverseRelations[entity.name] || []
    for (const inv of inverses) {
      const fromModel = pascalCase(inv.fromEntity)
      const invFieldName = `${inv.fromEntity}s_${inv.fieldName}`
      const relName = relationNames[inv.fromEntity]?.[inv.fieldName]
      const nameAttr = relName ? `@relation("${relName}")` : ""
      schema += `  ${invFieldName.padEnd(12)} ${fromModel}[] ${nameAttr}\n`
    }

    // Indexes
    if (foreignKeys.length > 0) {
      schema += "\n"
      for (const fk of foreignKeys) {
        schema += `  @@index([${fk}])\n`
      }
    }

    schema += "}\n"
  }

  return schema
}

export function generatePrismaSchema(
  entities: Entity[],
  options: { provider?: string } = {}
): string {
  const { provider = "sqlite" } = options

  let schema = `// =============================================================================
// GENERATED BY NEVR - DO NOT EDIT MANUALLY
// Regenerate with: npx nevr generate
// =============================================================================

generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "${provider}"
  url      = env("DATABASE_URL")
}
`

  // Build relation maps using the shared helper
  const { inverseRelations, relationNames } = buildRelationMaps(entities)

  for (const entityDef of entities) {
    const entity = resolveEntity(entityDef)
    const modelName = pascalCase(entity.name)

    schema += `\nmodel ${modelName} {\n`

    // ID field
    schema += `  id            String   @id @default(uuid())\n`

    // Regular fields
    for (const [fieldName, field] of Object.entries(entity.config.fields)) {
      // Skip hasMany relations (defined on other side)
      if (field.relation?.type === "hasMany") continue

      // Skip belongsTo (we'll add foreign key)
      if (field.relation?.type === "belongsTo") continue

      const prismaType = PRISMA_TYPES[field.type] || "String"
      let line = `  ${fieldName.padEnd(12)} ${prismaType}`

      if (field.optional) line += "?"

      // Add attributes
      const attrs: string[] = []
      if (field.unique) attrs.push("@unique")
      if (field.default !== undefined) {
        if (typeof field.default === "boolean") {
          attrs.push(`@default(${field.default})`)
        } else if (typeof field.default === "number") {
          attrs.push(`@default(${field.default})`)
        } else if (typeof field.default === "string") {
          attrs.push(`@default("${field.default}")`)
        }
      }

      if (attrs.length > 0) {
        line += " " + attrs.join(" ")
      }

      schema += line + "\n"
    }

    // Timestamps
    if (entity.config.timestamps) {
      schema += `  createdAt     DateTime @default(now())\n`
      schema += `  updatedAt     DateTime @updatedAt\n`
    }

    // Foreign keys and relations
    const foreignKeys: string[] = []

    for (const [fieldName, field] of Object.entries(entity.config.fields)) {
      if (!field.relation) continue

      // Resolve the related entity (might be Entity or EntityBuilder)
      const relatedEntityOrBuilder = field.relation.entity()
      if (!relatedEntityOrBuilder) {
        throw new Error(`[Generator] Cannot resolve entity for relation "${fieldName}" in entity "${entity.name}". The entity function returned undefined.`)
      }
      const relatedEntity = resolveEntity(relatedEntityOrBuilder)
      const relatedModel = pascalCase(relatedEntity.name)

      if (field.relation.type === "belongsTo") {
        const fk = field.relation.foreignKey
        foreignKeys.push(fk)

        // Foreign key field
        schema += `  ${fk.padEnd(12)} String${field.optional ? "?" : ""}\n`

        // Relation - add name if multiple relations to same entity
        const relName = relationNames[entity.name]?.[fieldName]
        const nameAttr = relName ? `"${relName}", ` : ""
        const onDelete = field.relation.onDelete
          ? `, onDelete: ${pascalCase(field.relation.onDelete)}`
          : ""
        schema += `  ${fieldName.padEnd(12)} ${relatedModel}? @relation(${nameAttr}fields: [${fk}], references: [id]${onDelete})\n`
      } else if (field.relation.type === "hasMany") {
        schema += `  ${fieldName.padEnd(12)} ${relatedModel}[]\n`
      } else if (field.relation.type === "hasOne") {
        schema += `  ${fieldName.padEnd(12)} ${relatedModel}?\n`
      }
    }

    // Add inverse relations (hasMany back-references)
    const inverses = inverseRelations[entity.name] || []
    for (const inv of inverses) {
      const fromModel = pascalCase(inv.fromEntity)
      const fieldName = `${inv.fromEntity}s_${inv.fieldName}` // e.g. "tasks_assignee"

      // Check if this relation needs a name (because source has multiple relations to this entity)
      const relName = relationNames[inv.fromEntity]?.[inv.fieldName]
      const nameAttr = relName ? `@relation("${relName}")` : ""

      schema += `  ${fieldName.padEnd(12)} ${fromModel}[] ${nameAttr}\n`
    }

    // Indexes for foreign keys
    if (foreignKeys.length > 0) {
      schema += "\n"
      for (const fk of foreignKeys) {
        schema += `  @@index([${fk}])\n`
      }
    }

    schema += "}\n"
  }

  return schema
}

