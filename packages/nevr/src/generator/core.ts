/**
 * Generate OpenAPI path for an entity action
 */
function generateActionPath(
  entity: Entity,
  actionName: string,
  action: EntityAction,
  basePath: string = ""
): Record<string, Record<string, unknown>> {
  const plural = pluralize(entity.name)
  const modelName = pascalCase(entity.name)
  const paths: Record<string, Record<string, unknown>> = {}

  // Build path based on whether action requires ID
  const pathSuffix = action.path || actionName
  const fullPath = action.requiresId
    ? `${basePath}/${plural}/{id}/${pathSuffix}`
    : `${basePath}/${plural}/${pathSuffix}`

  const method = action.method.toLowerCase()

  // Build request body schema if action has input
  let requestBody: Record<string, unknown> | undefined
  if (action.input && Object.keys(action.input).length > 0) {
    const properties: Record<string, unknown> = {}
    const required: string[] = []

    for (const [fieldName, field] of Object.entries(action.input)) {
      properties[fieldName] = fieldTypeToOpenAPI(field)
      if (!field.optional) {
        required.push(fieldName)
      }
    }

    requestBody = {
      required: true,
      content: {
        "application/json": {
          schema: {
            type: "object",
            properties,
            ...(required.length > 0 ? { required } : {}),
          },
        },
      },
    }
  }

  // Build parameters
  const parameters: Array<Record<string, unknown>> = []
  if (action.requiresId) {
    parameters.push({
      name: "id",
      in: "path",
      required: true,
      description: `The ${entity.name} ID`,
      schema: { type: "string", format: "uuid" },
    })
  }

  // Check if action requires auth
  const needsAuth = action.rules && action.rules.some(r => r !== "everyone")

  // Build extended description with operations info
  let description = action.metadata?.description || `Execute ${actionName} action`

  // Cast to access extended action properties (operations/returns from Entity-First pattern)
  const extAction = action as EntityAction & {
    operations?: Array<{ entity: string; operation: string; data?: unknown }>
    returns?: { entity?: string; pick?: string[]; omit?: string[] }
  }

  // Add operations info if present (Zero API pattern)
  if (extAction.operations && extAction.operations.length > 0) {
    const operationsInfo = extAction.operations.map(op => {
      const opType = op.operation.toUpperCase()
      const dataInfo = op.data === "auto" ? "(auto-mapped from input)" : "(custom data)"
      return `• ${opType} ${op.entity} ${dataInfo}`
    }).join("\n")

    description += `\n\n**Operations:**\n${operationsInfo}`
  }

  // Add returns info if present
  if (extAction.returns) {
    const returnsEntity = extAction.returns.entity || "all results"
    let returnsInfo = `Returns: ${returnsEntity}`
    if (extAction.returns.pick) {
      returnsInfo += ` (fields: ${extAction.returns.pick.join(", ")})`
    }
    if (extAction.returns.omit) {
      returnsInfo += ` (excluding: ${extAction.returns.omit.join(", ")})`
    }
    description += `\n\n**${returnsInfo}**`
  }

  // Build response schema based on returns config
  let responseSchema: Record<string, unknown> = { type: "object" }
  if (extAction.returns?.entity) {
    responseSchema = { $ref: `#/components/schemas/${pascalCase(extAction.returns.entity)}` }
  }

  const operation: Record<string, unknown> = {
    summary: action.metadata?.summary || `${actionName} action on ${entity.name}`,
    description,
    operationId: `${actionName}${modelName}`,
    tags: action.metadata?.tags || [modelName],
    ...(parameters.length > 0 ? { parameters } : {}),
    ...(requestBody ? { requestBody } : {}),
    responses: {
      "200": {
        description: "Action executed successfully",
        content: {
          "application/json": {
            schema: responseSchema,
          },
        },
      },
      "400": {
        description: "Validation error",
        content: {
          "application/json": {
            schema: { $ref: "#/components/schemas/Error" },
          },
        },
      },
    },
    ...(needsAuth ? { security: [{ bearerAuth: [] }] } : {}),
  }

  paths[fullPath] = { [method]: operation }

  return paths
}

/**
 * Generate OpenAPI path from a plugin route
 */
function generatePluginRoutePath(
  route: Route,
  pluginTag: string
): Record<string, Record<string, unknown>> {
  const paths: Record<string, Record<string, unknown>> = {}
  const method = route.method.toLowerCase()
  const pathPattern = route.path

  // Extract path parameters (e.g., :id -> {id})
  const openApiPath = pathPattern.replace(/:([a-zA-Z0-9_]+)/g, "{$1}")

  // Build parameters from path
  const parameters: Array<Record<string, unknown>> = []
  const paramMatches = pathPattern.match(/:([a-zA-Z0-9_]+)/g)
  if (paramMatches) {
    for (const match of paramMatches) {
      const paramName = match.slice(1) // Remove leading :
      parameters.push({
        name: paramName,
        in: "path",
        required: true,
        schema: { type: "string" },
      })
    }
  }

  // Use route metadata if available
  const meta = route.metadata || {}

  const operation: Record<string, unknown> = {
    summary: meta.summary || `${method.toUpperCase()} ${route.path}`,
    description: meta.description,
    operationId: meta.operationId || `${method}${openApiPath.replace(/[^a-zA-Z0-9]/g, "_")}`,
    tags: meta.tags || [pluginTag],
    ...(parameters.length > 0 ? { parameters } : {}),
    responses: meta.responses || {
      "200": {
        description: "Success",
      },
    },
    ...(meta.requiresAuth ? { security: [{ bearerAuth: [] }] } : {}),
    ...(meta.deprecated ? { deprecated: true } : {}),
  }

  // Add request body for POST/PUT/PATCH
  if (["post", "put", "patch"].includes(method)) {
    if (meta.requestBody) {
      operation.requestBody = meta.requestBody
    } else {
      operation.requestBody = {
        required: true,
        content: {
          "application/json": {
            schema: { type: "object" },
          },
        },
      }
    }
  }

  if (!paths[openApiPath]) {
    paths[openApiPath] = {}
  }
  paths[openApiPath][method] = operation

  return paths
}

/**
 * Generate complete OpenAPI 3.0 specification from entities
 *
 * @example
 * ```typescript
 * import { generateOpenAPI } from "nevr/generator"
 * import { user, post } from "./entities"
 *
 * const spec = generateOpenAPI([user, post], {
 *   info: {
 *     title: "My API",
 *     version: "1.0.0",
 *     description: "API generated by Nevr"
 *   },
 *   servers: [{ url: "http://localhost:3000" }],
 *   outPath: "./docs/openapi.json"
 * })
 * ```
 */
export function generateOpenAPI(
  entities: Entity[],
  options: OpenAPIGenerateOptions
): OpenAPISpec {
  const {
    info,
    servers,
    basePath = "/api",
    security = true,
    outPath,
  } = options

  const resolvedEntities = entities.map(resolveEntity)

  // Build schemas
  const schemas: Record<string, unknown> = {
    Error: {
      type: "object",
      properties: {
        code: {
          type: "string",
          description: "Error code",
          example: "VALIDATION_ERROR",
        },
        message: {
          type: "string",
          description: "Human-readable error message",
        },
        details: {
          type: "array",
          items: {
            type: "object",
            properties: {
              field: { type: "string" },
              message: { type: "string" },
            },
          },
        },
      },
      required: ["code", "message"],
    },
  }

  // Build paths
  let paths: Record<string, Record<string, unknown>> = {}

  // Build tags
  const tags: Array<{ name: string; description?: string }> = []

  for (const entity of resolvedEntities) {
    const modelName = pascalCase(entity.name)

    // Add schemas
    schemas[modelName] = generateEntitySchema(entity)
    schemas[`${modelName}Create`] = generateCreateInputSchema(entity)
    schemas[`${modelName}Update`] = generateUpdateInputSchema(entity)

    // Add paths
    paths = { ...paths, ...generateEntityPaths(entity, basePath) }

    // Add entity action paths
    if (entity.config.actions && Object.keys(entity.config.actions).length > 0) {
      for (const [actionName, action] of Object.entries(entity.config.actions)) {
        const actionPaths = generateActionPath(entity, actionName, action, basePath)
        paths = { ...paths, ...actionPaths }
      }
    }

    // Add tag
    tags.push({
      name: modelName,
      description: `Operations for ${pluralize(entity.name)}`,
    })
  }

  // Add plugin routes
  if (options.plugins && options.plugins.length > 0) {
    for (const plugin of options.plugins) {
      const pluginRoutes = typeof plugin.routes === "function"
        ? [] // Can't resolve without NevrInstance, skip function routes
        : plugin.routes || []

      const pluginTag = plugin.name || plugin.id || "Plugin"
      let hasRoutes = false

      for (const route of pluginRoutes) {
        const routePath = generatePluginRoutePath(route, pluginTag)
        for (const [pathKey, pathOps] of Object.entries(routePath)) {
          if (!paths[pathKey]) {
            paths[pathKey] = {}
          }
          paths[pathKey] = { ...paths[pathKey], ...pathOps }
        }
        hasRoutes = true
      }

      if (hasRoutes) {
        tags.push({
          name: pluginTag,
          description: plugin.description || `${pluginTag} plugin endpoints`,
        })
      }
    }
  }

  // Build spec
  const spec: OpenAPISpec = {
    openapi: "3.0.3",
    info,
    paths,
    components: {
      schemas,
      ...(security
        ? {
          securitySchemes: {
            bearerAuth: {
              type: "http",
              scheme: "bearer",
              bearerFormat: "JWT",
              description: "JWT authentication token",
            },
            cookieAuth: {
              type: "apiKey",
              in: "cookie",
              name: "session",
              description: "Session cookie authentication",
            },
          },
        }
        : {}),
    },
    tags,
  }

  if (servers) {
    spec.servers = servers
  }

  // Write to file if outPath provided
  if (outPath) {
    writeFile(outPath, JSON.stringify(spec, null, 2))
    console.log(`\n✅ OpenAPI spec written to: ${outPath}`)
  }

  return spec
}

