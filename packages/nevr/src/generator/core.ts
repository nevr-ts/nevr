/**
 * Generate only the database schema.
 * This is the recommended function to use - types and client are auto-synced.
 */
export function generateSchema(
  entities: Entity[],
  options: { outDir?: string; provider?: string } = {}
): { path: string; content: string } {
  const { outDir = "./prisma", provider = "sqlite" } = options

  const resolvedEntities = entities.map(resolveEntity)
  const content = generatePrismaSchema(resolvedEntities, { provider })
  const path = join(outDir, "schema.prisma")

  writeFile(path, content)

  return { path, content }
}

