interface EntityCache {
  version: string
  entities: Record<string, string> // entityName -> hash
  lastGenerated: string
}

const CACHE_VERSION = "1.0.0"
const CACHE_FILE = ".nevr-cache.json"

// -----------------------------------------------------------------------------
// Constants
// -----------------------------------------------------------------------------

const PRISMA_TYPES: Record<FieldType, string> = {
  string: "String",
  text: "String",
  int: "Int",
  float: "Float",
  boolean: "Boolean",
  datetime: "DateTime",
  json: "Json",
}

// -----------------------------------------------------------------------------
// Helpers
// -----------------------------------------------------------------------------

function ensureDir(dir: string): void {
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true })
  }
}

function writeFile(path: string, content: string): void {
  ensureDir(dirname(path))
  writeFileSync(path, content, "utf-8")
}

// -----------------------------------------------------------------------------
// Cache Helpers
// -----------------------------------------------------------------------------

/**
 * Generate a hash for an entity's configuration
 */
function hashEntity(entity: Entity): string {
  const data = JSON.stringify({
    name: entity.name,
    config: entity.config,
  })
  return createHash("md5").update(data).digest("hex")
}

/**
 * Load cache from file
 */
function loadCache(outDir: string): EntityCache | null {
  const cachePath = join(outDir, CACHE_FILE)
  if (!existsSync(cachePath)) return null

  try {
    const content = readFileSync(cachePath, "utf-8")
    const cache = JSON.parse(content) as EntityCache
    if (cache.version !== CACHE_VERSION) return null
    return cache
  } catch {
    return null
  }
}

/**
 * Save cache to file
 */
function saveCache(outDir: string, cache: EntityCache): void {
  const cachePath = join(outDir, CACHE_FILE)
  ensureDir(outDir)
  writeFileSync(cachePath, JSON.stringify(cache, null, 2), "utf-8")
}

/**
 * Check which entities have changed since last generation
 */
function getChangedEntities(
  entities: Entity[],
  cache: EntityCache | null
): { changed: Entity[]; unchanged: Entity[]; isFullRebuild: boolean } {
  if (!cache) {
    return { changed: entities, unchanged: [], isFullRebuild: true }
  }

  const changed: Entity[] = []
  const unchanged: Entity[] = []

  for (const entity of entities) {
    const currentHash = hashEntity(entity)
    const cachedHash = cache.entities[entity.name]

    if (cachedHash === currentHash) {
      unchanged.push(entity)
    } else {
      changed.push(entity)
    }
  }

  // Check for removed entities
  const currentNames = new Set(entities.map(e => e.name))
  const removedEntities = Object.keys(cache.entities).filter(name => !currentNames.has(name))

  // If entities were removed, we need a full rebuild
  if (removedEntities.length > 0) {
    return { changed: entities, unchanged: [], isFullRebuild: true }
  }

  return { changed, unchanged, isFullRebuild: false }
}

/**
 * Build new cache from entities
 */
function buildCache(entities: Entity[]): EntityCache {
  const entityHashes: Record<string, string> = {}
  for (const entity of entities) {
    entityHashes[entity.name] = hashEntity(entity)
  }

  return {
    version: CACHE_VERSION,
    entities: entityHashes,
    lastGenerated: new Date().toISOString(),
  }
}

