export interface GenerateOptions {
  /**
   * Output directory for generated files.
   * For Prisma driver, defaults to "./prisma"
   * Schema will be output as: {outDir}/schema.prisma
   */
  outDir?: string
  /**
   * Database provider for Prisma schema.
   * @default "sqlite"
   */
  prismaProvider?: "sqlite" | "postgresql" | "mysql"
  /**
   * Driver type - determines output folder structure.
   * @default "prisma"
   */
  driver?: "prisma"
  /**
   * Enable schema splitting for large codebases (100+ entities).
   * Uses Prisma's prismaSchemaFolder feature to split schema by namespace.
   * Entities are grouped by their .namespace() setting.
   * @default false (auto-enabled if entities have namespaces)
   */
  splitSchema?: boolean
  /**
   * Enable incremental generation with caching.
   * Only regenerates schema when entities have changed.
   * Stores cache in .nevr-cache.json in the output directory.
   * @default true
   */
  incremental?: boolean
  /**
   * Force full regeneration, ignoring cache.
   * @default false
   */
  force?: boolean
}

export interface GenerateResult {
  files: string[]
  schemaPath: string
  /** When splitSchema is enabled, contains paths to all namespace schema files */
  namespaceFiles?: Record<string, string>
  /** Incremental generation info */
  cache?: {
    wasIncremental: boolean
    changedEntities: string[]
    unchangedEntities: string[]
    skipped: boolean
  }
}

/**
 * Generate database schema from entities.
 *
 * NOTE: Types and API client are no longer generated - they are automatically
 * synced from server to client through NEVR's type inference system.
 *
 * @example
 * ```typescript
 * import { generate } from "nevr/generator"
 * import { user, post } from "./entities"
 *
 * // Generates schema to ./prisma/schema.prisma (default)
 * generate([user, post])
 *
 * // Custom output directory
 * generate([user, post], { outDir: "./db" })
 * ```
 */
export function generate(
  entities: Entity[],
  options: GenerateOptions = {}
): GenerateResult {
  const {
    driver = "prisma",
    prismaProvider = "sqlite",
    incremental = true,
    force = false,
  } = options

  // Default output directory based on driver
  // For prisma driver, output to ./prisma folder (standard convention)
  const outDir = options.outDir || (driver === "prisma" ? "./prisma" : "./generated")

  const files: string[] = []

  // Resolve all entities
  const resolvedEntities = entities.map(resolveEntity)

  // Check if any entities have namespaces
  const hasNamespaces = resolvedEntities.some(e => e.config.namespace)
  const shouldSplit = options.splitSchema ?? hasNamespaces

  console.log("\n🔧 nevr generate\n")

  // Incremental generation with caching
  let cacheInfo: GenerateResult["cache"] = undefined
  if (incremental && !force) {
    const cache = loadCache(outDir)
    const { changed, unchanged, isFullRebuild } = getChangedEntities(resolvedEntities, cache)

    if (changed.length === 0 && !isFullRebuild) {
      console.log(`   ⚡ No changes detected - skipping generation`)
      console.log(`   ${unchanged.length} entities unchanged\n`)

      // Return cached result
      const schemaPath = shouldSplit
        ? join(outDir, "schema", "schema.prisma")
        : join(outDir, "schema.prisma")

      return {
        files: [],
        schemaPath,
        cache: {
          wasIncremental: true,
          changedEntities: [],
          unchangedEntities: unchanged.map(e => e.name),
          skipped: true,
        },
      }
    }

    if (!isFullRebuild && changed.length < resolvedEntities.length) {
      console.log(`   ⚡ Incremental: ${changed.length} changed, ${unchanged.length} unchanged`)
      cacheInfo = {
        wasIncremental: true,
        changedEntities: changed.map(e => e.name),
        unchangedEntities: unchanged.map(e => e.name),
        skipped: false,
      }
    }
  }

  console.log(`   Found ${resolvedEntities.length} entities:`)
  resolvedEntities.forEach(e => {
    const ns = e.config.namespace ? ` (${e.config.namespace})` : ""
    console.log(`   - ${e.name}${ns}`)
  })
  console.log()

  let schemaPath: string
  let namespaceFiles: Record<string, string> | undefined

  if (shouldSplit) {
    // Split schema by namespace
    namespaceFiles = {}

    // Group entities by namespace
    const namespaceMap: Record<string, Entity[]> = { _default: [] }
    for (const entity of resolvedEntities) {
      const ns = entity.config.namespace || "_default"
      if (!namespaceMap[ns]) namespaceMap[ns] = []
      namespaceMap[ns].push(entity)
    }

    const namespaces = Object.keys(namespaceMap).filter(ns => namespaceMap[ns].length > 0)
    console.log(`   📂 Schema splitting enabled (${namespaces.length} namespaces)`)

    // Create schema directory
    const schemaDir = join(outDir, "schema")
    ensureDir(schemaDir)

    // Generate main schema.prisma with header only
    schemaPath = join(schemaDir, "schema.prisma")
    const header = generatePrismaHeader({ provider: prismaProvider, splitSchema: true })
    writeFile(schemaPath, header)
    files.push(schemaPath)
    console.log(`   ✅ ${schemaPath} (config)`)

    // Generate namespace-specific schema files
    for (const ns of namespaces) {
      const nsEntities = namespaceMap[ns]
      const fileName = ns === "_default" ? "models.prisma" : `${ns}.prisma`
      const nsPath = join(schemaDir, fileName)

      const nsHeader = `// =============================================================================
// NAMESPACE: ${ns === "_default" ? "default" : ns}
// Entities: ${nsEntities.map(e => e.name).join(", ")}
// =============================================================================
`
      const models = generatePrismaModels(nsEntities, resolvedEntities)
      writeFile(nsPath, nsHeader + models)
      files.push(nsPath)
      namespaceFiles[ns] = nsPath
      console.log(`   ✅ ${nsPath} (${nsEntities.length} models)`)
    }

    console.log(`
   ℹ️  Schema splitting is enabled using Prisma's prismaSchemaFolder feature.
   All .prisma files in ${schemaDir} are combined into one schema.

   Next steps:
   1. Run: npx prisma db push
   2. Run: npm run dev

   Benefits of schema splitting:
   - Faster schema generation for large codebases
   - Better organization by domain/namespace
   - Parallel team development on different namespaces
`)
  } else {
    // Generate single schema file
    schemaPath = join(outDir, "schema.prisma")
    writeFile(schemaPath, generatePrismaSchema(resolvedEntities, { provider: prismaProvider }))
    files.push(schemaPath)
    console.log(`   ✅ ${schemaPath}`)

    console.log(`
   ℹ️  Types and API client are no longer generated.
   They are automatically synced from server to client.

   Next steps:
   1. Run: npx prisma db push
   2. Run: npm run dev

   💡 Tip: For large codebases (100+ entities), use .namespace() on entities
   to enable schema splitting for better performance.
`)
  }

  // Save cache for incremental generation
  if (incremental) {
    const newCache = buildCache(resolvedEntities)
    saveCache(outDir, newCache)
  }

  return { files, schemaPath, namespaceFiles, cache: cacheInfo }
}

